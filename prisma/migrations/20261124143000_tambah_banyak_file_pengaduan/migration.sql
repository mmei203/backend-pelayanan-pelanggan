CREATE TABLE `TABEL_PENGADUAN_FILE_ITEM` (
    `ID_FILE` VARCHAR(36) NOT NULL,
    `ID_PENGADUAN` VARCHAR(36) NOT NULL,
    `JENIS_FILE` VARCHAR(20) NOT NULL,
    `NAMA_FILE` VARCHAR(255) NOT NULL,
    `MIME_TYPE` VARCHAR(100) NOT NULL,
    `FILE_DATA` MEDIUMBLOB NOT NULL,
    `CREATED_AT` TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`ID_FILE`),
    INDEX `TABEL_PENGADUAN_FILE_ITEM_ID_PENGADUAN_JENIS_FILE_idx` (`ID_PENGADUAN`, `JENIS_FILE`),
    CONSTRAINT `TABEL_PENGADUAN_FILE_ITEM_ID_PENGADUAN_fkey`
        FOREIGN KEY (`ID_PENGADUAN`) REFERENCES `TABEL_PENGADUAN` (`ID_PENGADUAN`)
        ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;
